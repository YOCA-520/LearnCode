// ============================================================
// todo.h —— 待办任务的数据结构定义
//
// 这个头文件只做一件事：定义"一条待办任务"长什么样（Todo 结构体）。
// 它不包含任何逻辑，只是数据类型的"图纸"。
//
// 为什么单独放在一个头文件里？
// 因为很多文件都要用到 Todo 这种类型：
//   - todo_manager.h 里要用 std::vector<Todo> 管理任务列表
//   - utils.h / utils.cpp 里要把 Todo 转成 JSON、从 JSON 还原
//   如果把 Todo 定义在某个 .cpp 里，别的文件就用不了了，
//   所以单独放一个头文件，谁需要谁就 #include 它。
// ============================================================

#pragma once
// #pragma once 的意思是"本文件只编译一次"。
// 防止多个文件互相 #include 导致同一个头文件被重复包含而报错
// （编译器会提示"重复定义"错误）。

#include <string>
// 引入 std::string（字符串类型），因为任务标题、类别都要用字符串。

// ------------------------------------------------------------------
// Todo：一条待办任务的数据结构
// struct（结构体）和 class（类）很相似，区别只是成员默认公有/私有。
// 这里用 struct 表示"我只是一个装数据的盒子"，没有行为（函数）。
// ------------------------------------------------------------------
struct Todo {
	std::string title;      // 任务标题，例如"写周报"
	std::string category;   // 类别代码，例如 "work"（工作）、"life"（生活）、"study"（学习）
	int priority = 1;       // 优先级 1～5，数字越大越重要（默认 1，最低）
	bool done = false;      // 是否已完成（默认 false = 还没完成）
};

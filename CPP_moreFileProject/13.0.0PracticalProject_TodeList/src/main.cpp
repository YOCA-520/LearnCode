// ============================================================
// main.cpp —— 程序入口
//
// 每个 C++ 程序只能有一个 main 函数，程序就从这里开始执行。
// 本文件非常"薄"：真正的逻辑都在 TodoManager 里，
// main 只做三件事：
//   1. 创建 TodoManager 对象
//   2. 调用 run() 进入主循环
//   3. 捕获意外异常，友好地提示用户后退出
//
// 这种"main 尽量简单"的写法是良好的工程习惯：
// 可测试性更好、main 文件越短越不容易出错。
// ============================================================

#include "todo_manager.h"
// 引入 TodoManager 类的声明（要用它创建管理器对象）。
#include <exception>
// std::exception：C++ 标准异常类型的基类，用于 catch 捕获。
#include <iostream>
// std::cin / std::cout / std::cerr 的声明（标准输入输出）。

int main() {
    // try 块：把可能出错的代码放进来，出错时会被下面的 catch 接住。
    // 这里即使没有 try，程序崩了也会终止，但那样用户看到的
    // 是冷冰冰的崩溃信息；有了 try-catch 就能给出友好的中文提示。
    try {
        TodoManager manager;
        // 创建待办清单管理器。
        // 此时 TodoManager 的成员 logger_ 会被自动初始化（打开日志文件），
        // 但任务列表还是空的，真正的加载发生在 run() 里。

        manager.run();
        // 进入主循环：显示菜单、处理用户选择，直到用户选择"0. 退出"。
        // run() 内部会自己处理保存和退出，所以这里只需这一行。

        return 0;
        // 正常退出，返回 0 表示"程序运行成功"（操作系统约定的惯例）。
    } catch (const std::exception& error) {
        // 捕获所有"标准异常"（比如内存不足、JSON 库内部错误等）。
        // error.what() 返回异常的描述文字。
        std::cerr << "程序发生未处理错误：" << error.what() << '\n';
        // cerr 是"错误输出流"，和 cout 一样能打印，但专用于错误信息
        // （重定向输出时 cerr 不会跟着走，错误依然显示在屏幕上）。
        return 1;
        // 返回 1 表示"程序异常结束"（非 0 即失败）。
    } catch (...) {
        // 兜底：捕获"任何其他异常"（... 是通配符，匹配所有类型）。
        // 有些异常不是 std::exception 的子类，只有这个兜底能接住。
        std::cerr << "程序发生未知错误。\n";
        return 1;
    }
}
